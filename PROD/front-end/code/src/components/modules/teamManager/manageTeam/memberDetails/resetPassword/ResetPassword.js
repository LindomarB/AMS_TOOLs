import React, { useContext} from 'react';
import Button from '../../../../../Interface/buttons/button/Button';
import UserContext from '../../../../../context/userContext/UserContext';
import SettingSection from '../../../../settings/components/settingSection/SettingSection';
import Text from '../../../../../Interface/Text/Text';
import FetcherContext from '../../../../../context/fetcherContext/FetcherContext';
import InputButton from '../../../../../Interface/containers/inputButton/InputButton';
import useInput from '../../../../../hooks/useInput';
import TextInput from '../../../../../Interface/inputs/textInput/TextInput';
import LoadableContent from '../../../../../Interface/containers/loadableContent/LoadableContent';
import CopyButton from '../../../../../Interface/buttons/copyButton/CopyButton';
import style from './ResetPassword.module.css';

function ResetPassword(props) {
    const user = useContext(UserContext).user;
    const fetcher = useContext(FetcherContext);

    // useEffect(() => {
    //     props.refreshUser();
    // }, []);

    const password = useInput({
        name: 'password', 
        required: true
    });

    const getLink = async () => {
        await fetcher.generateMemberPasswordResetLink({
            userId: props.member._id,
            password: password.value
        });

        props.refreshUser();
    }

    const passwordReset = props.member.settings['password reset'];
    const link = passwordReset && `${process.env.REACT_APP_FRONTEND_SERVER}/portal/reset-password?authorization=${passwordReset.authorization}`;

    const sendEmail = () => {
        const to = props.member.profile.email;
        const subject = 'AMS Tools - Password reset';
        const body = [
            `Hello ${props.member.profile.name},%0D%0A`,
            `You have requested to reset your password. Click on the link below to set a new:%0D%0A`,
            link,
            `%0D%0AThis link is valid for 72 hours, expiring on ${new Date(new Date().getTime() + 259200000).toUTCString()}.`,
            `If you have not made this request, please let me know.%0D%0A`,
            `Best regards,`,
            `${user.profile.name}%0D%0A`,
            `This email was automatically generated by AMS Tools.`
        ].join('%0D%0A');

        window.location.href = `mailto:${to}?subject=${subject}&body=${body}`;
    }

    return (
        <LoadableContent loading={fetcher.awaiting.refreshUser}>
            <SettingSection title='Reset Password'>
                {passwordReset.requested &&
                    <>
                        <Text color='grey'>
                            {props.member.profile.name} forgot his/her password and asked for your help.<br/>
                            Click the 'Request Password Reset' button to generate a link so he/she can set a new password. It will be valid for 72 hours.
                        </Text>
                        <InputButton className={style.inputButton}>
                            <TextInput
                                className={style.input}
                                type='password'
                                input={password}
                                placeholder='Type your password to proceed'
                                onPressEnter={getLink} 
                            />
                            <Button
                                color='green' 
                                disabled={!password.isValid} 
                                onClick={getLink}
                                awaiting={fetcher.awaiting.generateMemberPasswordResetLink || fetcher.awaiting.refreshUser}
                            >
                                Request Password Reset
                            </Button>
                        </InputButton>
                        <Text color='grey'>
                            This request was made on 
                            <Text span color='grey' weight={600}> {new Date(passwordReset.date).toLocaleString()} </Text>
                            and you can request the password reset until
                            <Text span color='grey' weight={600}> {new Date(passwordReset.expiration).toLocaleString()}</Text>.
                        </Text>
                    </>
                }
                {passwordReset.authorization &&
                    <>
                        <Text color='grey'>
                            A link has been generated for {props.member.profile.name} to reset your password. Choose how you want to inform him/her:
                        </Text>
                        <Button
                            className={style.button}
                            icon='mail'
                            color='blue'
                            onClick={sendEmail}
                        >
                            Send link by email
                        </Button>
                        <CopyButton
                            className={style.button}
                            text={link}
                            color='blue'
                        >
                            Copy link
                        </CopyButton>
                        <Text color='grey'>
                            The link was created on 
                            <Text span color='grey' weight={600}> {new Date(passwordReset.date).toLocaleString()} </Text>
                            and will expire on
                            <Text span color='grey' weight={600}> {new Date(passwordReset.expiration).toLocaleString()}</Text>.
                        </Text>
                    </>
                }
            </SettingSection>
        </LoadableContent>
    )
}

export default ResetPassword;